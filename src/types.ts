/**
 * Модель данных маргинальных комментариев.
 */

export interface SideComment {
	/** Уникальный идентификатор комментария. */
	id: string;
	/** Путь к файлу заметки, к которой привязан комментарий. */
	file: string;
	/** Начальное смещение выделенного фрагмента в документе. */
	from: number;
	/** Конечное смещение выделенного фрагмента в документе. */
	to: number;
	/** Выделенный текст (для отображения в списке и поиска позиции). */
	text: string;
	/** Тело комментария. */
	comment: string;
	/** Время создания (timestamp, мс). */
	createdAt: number;
	/** Время последнего обновления (timestamp, мс). */
	updatedAt: number;
}

/**
 * Хранилище комментариев, сгруппированных по пути к файлу.
 */
export type CommentsStore = Record<string, SideComment[]>;
